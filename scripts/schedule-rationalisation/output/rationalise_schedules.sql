SELECT m.*, sv.ScheduleId AS SurvivorScheduleId, rt.ScheduleId AS RetiredScheduleId
INTO #Map
FROM #Merge m JOIN dbo.tblBulkRunSchedule sv ON sv.BulkRunScheduleId = m.SurvivorRowId JOIN dbo.tblBulkRunSchedule rt ON rt.BulkRunScheduleId = m.RetiredRowId;

-- 2. Safety checks. Every SELECT must return 0 rows before @Commit is set to 1.
--    a) every pair resolved to two different, live schedules
SELECT m.* FROM #Merge m LEFT JOIN #Map p ON p.RetiredRowId = m.RetiredRowId WHERE p.RetiredRowId IS NULL OR p.SurvivorScheduleId = p.RetiredScheduleId;
SELECT p.* FROM #Map p JOIN dbo.tblBulkRunScheduleHeader h ON h.ScheduleId IN (p.SurvivorScheduleId, p.RetiredScheduleId) WHERE h.RetiredUtc IS NOT NULL;
--    b) the retired schedule still belongs to the client we expect (export not stale)
SELECT p.* FROM #Map p JOIN dbo.tblBulkRunScheduleHeader h ON h.ScheduleId = p.RetiredScheduleId WHERE ISNULL(h.LegacyClientId, -1) <> p.ClientId;
--    c) retired schedules that own zone / linehaul rows (NOT compared by this script - the survivor may differ)
SELECT z.* FROM dbo.BulkZoneSchedule z JOIN dbo.tblBulkRunSchedule s ON s.BulkRunScheduleId = z.ScheduleId JOIN #Map p ON p.RetiredScheduleId = s.ScheduleId;
-- SELECT l.* FROM dbo.tblBulkScheduleLinehaul l JOIN dbo.tblBulkRunSchedule s ON s.BulkRunScheduleId = l.<schedule id column> JOIN #Map p ON p.RetiredScheduleId = s.ScheduleId;

-- 3. Re-point link rows from the retired schedule to the survivor.
INSERT INTO dbo.tblBulkRunScheduleClient (ScheduleId, ClientId, CreatedUtc, CreatedBy)
SELECT p.SurvivorScheduleId, l.ClientId, '2026-09-08T02:00:00Z', @By
FROM dbo.tblBulkRunScheduleClient l JOIN #Map p ON p.RetiredScheduleId = l.ScheduleId
WHERE NOT EXISTS (SELECT 1 FROM dbo.tblBulkRunScheduleClient x WHERE x.ScheduleId = p.SurvivorScheduleId AND x.ClientId = l.ClientId);
DELETE l FROM dbo.tblBulkRunScheduleClient l JOIN #Map p ON p.RetiredScheduleId = l.ScheduleId;

-- 4. Retire the copies: header marked, day rows removed (the survivor's rows are identical).
DELETE s FROM dbo.tblBulkRunSchedule s JOIN #Map p ON p.RetiredScheduleId = s.ScheduleId;
UPDATE h SET RetiredUtc = '2026-09-08T02:00:00Z', RetiredBy = @By FROM dbo.tblBulkRunScheduleHeader h JOIN #Map p ON p.RetiredScheduleId = h.ScheduleId;

-- 5. Result.
SELECT (SELECT COUNT(*) FROM #Map) AS SchedulesRetired, (SELECT COUNT(*) FROM dbo.tblBulkRunScheduleHeader WHERE RetiredUtc IS NULL) AS LiveSchedules,
       (SELECT COUNT(*) FROM dbo.tblBulkRunSchedule) AS DayRows, (SELECT COUNT(*) FROM dbo.tblBulkRunScheduleClient) AS LinkRows;
