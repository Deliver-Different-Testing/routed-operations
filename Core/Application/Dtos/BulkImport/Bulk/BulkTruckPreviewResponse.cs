using RoutedOperations.Core.Application.Dtos.BulkImport.Common;

namespace RoutedOperations.Core.Application.Dtos.BulkImport.Bulk
{
    // POST /api/bulk-import/truck-preview. The request is a BulkImportRequest, the
    // same body /import takes.
    public class BulkTruckPreviewResponse : BaseResponse
    {
        public BulkTruckPreviewResponse(Guid messageId) : base(messageId)
        {
        }

        // One per truck row, plus any row the truck split refused, in file order.
        public List<BulkTruckPreviewRow> Rows { get; set; } = new();

        // Rows that stay on the P2P path, which are priced at import as before.
        public int OtherRowCount { get; set; }
    }

    public class BulkTruckPreviewRow
    {
        // Position in the request's Jobs list.
        public int RowIndex { get; set; }

        // Null when the number is autogenerated, since it is only assigned at import.
        public string? JobNumber { get; set; }
        public string? SpeedName { get; set; }
        public string? FromSuburb { get; set; }
        public string? ToSuburb { get; set; }
        public int? Quantity { get; set; }

        // The rate and fuel behind Amount. Both null when staff entered the amount.
        public decimal? Rate { get; set; }
        public decimal? Fuel { get; set; }

        // What the insert would write to ucjbAmount. Null when the row would be rejected.
        public decimal? Amount { get; set; }
        public bool RatedManually { get; set; }

        public bool WouldImport { get; set; }

        // Why the row would be rejected. Null when WouldImport is true.
        public string? Reason { get; set; }

        // A row that imports but is worth a look, such as an unrecognised suburb.
        public string? Warning { get; set; }
    }
}
