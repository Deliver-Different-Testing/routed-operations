// Truck price preview (card bulk-insert-truck-and-ai, spec A4). Runs the insert's
// own split, input build and plan stages and stops before BulkTruckInserter, so the
// amount shown is the amount the insert would write. Writes nothing to the database.
using Microsoft.EntityFrameworkCore;
using RoutedOperations.Core.Application.Dtos.BulkImport.Bulk;
using RoutedOperations.Core.Application.Utilities;
using Serilog;

namespace RoutedOperations.Core.Application.Services.BulkImport;

public partial class BulkImportServiceV2
{
    private const string AutogenerateJobNumber = "AUTOGENERATE";

    public async Task<BulkTruckPreviewResponse> PreviewTruckRows(int contactId, BulkImportRequest request)
    {
        var response = new BulkTruckPreviewResponse(request.MessageId);

        PrepareImportRequest(contactId, request);
        dynamic? client = await LoadImportClient(contactId, request);

        // Routed and US imports have no truck path, so there is nothing to preview.
        if (!IsNzTenant() || !string.Equals(request.JobType, "ondemand", StringComparison.OrdinalIgnoreCase))
        {
            if (client == null)
                return BulkImportResponseUtility.AddMessageAndReturnResponse(response, "Invalid client.");
            response.OtherRowCount = request.Jobs?.Count() ?? 0;
            response.Success = true;
            return response;
        }

        string? refused = OnDemandRefusal(contactId, request, client);
        if (refused != null)
            return BulkImportResponseUtility.AddMessageAndReturnResponse(response, refused);

        var jobs = (request.Jobs ?? Enumerable.Empty<BulkImportJobCreateDto>()).ToList();
        request.Jobs = jobs;
        if (jobs.Count == 0)
            return BulkImportResponseUtility.AddMessageAndReturnResponse(response, "No jobs to import.");

        var indexOf = new Dictionary<BulkImportJobCreateDto, int>(ReferenceEqualityComparer.Instance);
        for (int i = 0; i < jobs.Count; i++) indexOf[jobs[i]] = i;

        // sp_AssignJobNumbers consumes numbers, so it is left for /import. Each row
        // gets a stand-in that cannot clash with another row or with a real job.
        var autogenerated = jobs.Where(j => j.JobNumber?.Trim().ToUpper() == AutogenerateJobNumber).ToHashSet();
        foreach (var job in autogenerated)
            job.JobNumber = $"{AutogenerateJobNumber}-{indexOf[job]}";

        // Same check, same place as /import, so the preview shows the same refusal.
        var refusedByReference = await SplitOutReferenceRefusals(request);
        var split = await SplitTruckRows(request);
        response.OtherRowCount = split.P2PRows.Count;

        var failed = new List<(int RowNo, string Error)>();
        var inputs = new List<TruckRowInput>();
        TruckPlan? plan = null;
        if (split.TruckRows.Count > 0)
        {
            DateTime bookTime = TruckBookTime(request, client);
            inputs = await BuildWizardTruckInputs(contactId, request, split.TruckRows, bookTime, opId: null, podName: null);
            try
            {
                plan = await PlanTruckRows(inputs, failed);
            }
            catch (Exception ex)
            {
                Log.Error(ex, "({MessageId}) [TruckPreview] Truck batch failed", request.MessageId);
                FailEveryOtherRow(inputs, failed, ex);
            }
        }

        var ready = (plan?.Ready ?? new List<TruckInsertRow>()).ToDictionary(r => r.RowNo);
        var speedIds = inputs.Select(i => i.SpeedId)
            .Concat(ready.Values.Select(r => r.ucjbSpeed))
            .Distinct()
            .ToList();
        var speedNames = speedIds.Count == 0
            ? new Dictionary<int, string?>()
            : await Context.TucJobTypes
                .Where(t => speedIds.Contains(t.UcjtId))
                .ToDictionaryAsync(t => t.UcjtId, t => (string?)t.UcjtName);

        // Steve ruling 6. A customer gets what the booking page shows them, decided
        // here so the rate and fuel never leave the server for a customer login.
        bool customer = !_scope.IsStaff;
        response.CustomerPricing = customer;
        IReadOnlyDictionary<int, string?> publicDescriptions = customer && plan != null
            ? await _truckPreflight.PublicDescriptionsAsync(PublicRateRows(plan))
            : new Dictionary<int, string?>();

        BulkTruckPreviewRow Row(BulkImportJobCreateDto job) => new()
        {
            RowIndex = indexOf[job],
            JobNumber = autogenerated.Contains(job) ? null : job.JobNumber?.Trim(),
            SpeedName = job.Speed,
            FromSuburb = job.FromSuburb,
            ToSuburb = job.ToSuburb,
            Quantity = job.Quantity,
        };

        var rows = refusedByReference.Concat(split.Rejected).Select(job =>
        {
            var row = Row(job);
            row.Reason = job.ErrorMessage;
            return row;
        }).ToList();

        var reasons = failed.ToDictionary(f => f.RowNo, f => f.Error);
        foreach (var input in inputs)
        {
            var row = Row(input.Job);
            // Prepare may have filled the quantity's default, so read it from the plan's row.
            if (ready.TryGetValue(input.RowNo, out var insert))
            {
                var pre = plan!.Preflight[input.RowNo];
                row.WouldImport = true;
                row.SpeedName = speedNames.GetValueOrDefault(insert.ucjbSpeed) ?? row.SpeedName;
                row.FromSuburb = insert.PickupAddressLine5 ?? row.FromSuburb;
                row.ToSuburb = insert.DeliveryAddressLine5 ?? row.ToSuburb;
                row.Quantity = insert.ucjbQty;
                row.Amount = insert.ucjbAmount;
                row.RatedManually = insert.RatedManually;
                row.Rate = insert.RatedManually || customer ? null : pre.Rate;
                row.Fuel = insert.RatedManually || customer ? null : pre.Fuel;
                row.Warning = insert.Warning;
                row.WarningLevel = insert.WarningLevel;
                if (customer)
                {
                    row.AmountInclGst = TruckRowCalculator.AmountInclGst(insert.ucjbAmount);
                    row.PriceLines = TruckRowCalculator.ParsePriceLines(publicDescriptions.GetValueOrDefault(input.RowNo)).ToList();
                }
            }
            else
            {
                row.SpeedName = speedNames.GetValueOrDefault(input.SpeedId) ?? row.SpeedName;
                row.Reason = reasons.GetValueOrDefault(input.RowNo) ?? "The truck rate check returned nothing for this row.";
            }
            rows.Add(row);
        }

        response.Rows = rows.OrderBy(r => r.RowIndex).ToList();
        response.Success = true;
        Log.Information("({MessageId}) [TruckPreview] {Rows} truck rows, {WouldImport} would import, {Other} other rows",
            request.MessageId, response.Rows.Count, response.Rows.Count(r => r.WouldImport), response.OtherRowCount);
        return response;
    }

    private static List<TruckPublicRateRow> PublicRateRows(TruckPlan plan)
    {
        var plans = plan.Plans.ToDictionary(p => p.Input.RowNo);
        return plan.Ready.Select(r =>
        {
            var p = plans[r.RowNo];
            return new TruckPublicRateRow(
                r.RowNo, r.ucjbClientID, r.ucjbFrom, r.ucjbTo, r.ucjbSpeed, p.TotalWeight, p.Quantity,
                p.TailLiftPickupCount, p.TailLiftDropoffCount, p.Input.BookDateTime, p.OverSizeItems, p.OverWeightItems,
                p.Residential, p.DangerousGoods, p.TruckStart, p.TruckHours);
        }).ToList();
    }
}
